import streamlit as st
import pandas as pd

# ---------------------------------------------------------
# 1. 데이터 정의 (리스트와 딕셔너리 활용)
# ---------------------------------------------------------
# [기준 기록, 배점] 형태의 2차원 리스트 (높은 점수부터 순서대로 배치)
SCORE_TABLE = {
    "남자": {
        "10m": [
            [8.20, 100], [8.35, 95], [8.50, 90], [8.65, 85],
            [8.80, 80], [8.95, 75], [9.10, 70], [9.25, 65], [9.40, 60]
        ],
        "제자리 멀리뛰기": [
            [295, 100], [290, 95], [285, 90], [280, 85],
            [275, 80], [270, 75], [265, 70], [260, 65], [255, 60]
        ]
    },
    "여자": {
        "10m": [
            [9.10, 100], [9.30, 95], [9.50, 90], [9.70, 85],
            [9.90, 80], [10.10, 75], [10.30, 70], [10.50, 65], [10.70, 60]
        ],
        "제자리 멀리뛰기": [
            [245, 100], [240, 95], [235, 90], [230, 85],
            [225, 80], [220, 75], [215, 70], [210, 65], [205, 60]
        ]
    }
}

# [보강운동, 횟수, 주기] 형태의 2차원 리스트
TRAINING_GUIDE = {
    "10m": [
        ["사다리 스텝 훈련 (민첩성)", "5세트 (왕복)", "주 3회"],
        ["스타트 대시 (15m 전력질주)", "8회", "주 3회"],
        ["사이드 스텝 & 콘 터치", "30초 x 4세트", "주 2회"],
        ["박스 점프 & 착지", "12회 x 3세트", "주 2회"]
    ],
    "제자리 멀리뛰기": [
        ["스쿼트 점프 (순발력)", "15회 x 4세트", "주 3회"],
        ["버피 테스트", "15회 x 3세트", "주 3회"],
        ["행잉 레그레이즈 (코어 탄력)", "15회 x 4세트", "주 3회"],
        ["카프 레이즈 (발목 반발력)", "20회 x 4세트", "주 4회"]
    ]
}


# ---------------------------------------------------------
# 2. 점수 계산 함수 (함수, 반복문, 조건문 활용)
# ---------------------------------------------------------
def calculate_score(gender, event, record):
    # 선택한 성별과 종목에 해당하는 배점 기준 리스트 가져오기
    criteria_list = SCORE_TABLE[gender][event]
    
    # 반복문(for)으로 배점 기준표를 위에서부터 하나씩 비교
    for standard, score in criteria_list:
        if event == "10m":
            # 10m 왕복달리기는 기록이 작을수록(빠를수록) 점수 획득
            if record <= standard:
                return score
        elif event == "제자리 멀리뛰기":
            # 제자리 멀리뛰기는 기록이 클수록(멀수록) 점수 획득
            if record >= standard:
                return score
                
    # 최저 기준(60점)에 미치지 못할 경우 기본 50점 반환
    return 50


# ---------------------------------------------------------
# 3. 메인 웹 화면 구성 함수 (함수, 조건문, 반복문 활용)
# ---------------------------------------------------------
def main():
    st.set_page_config(page_title="체대입시 실기 가이드", page_icon="🏃‍♂️")
    
    st.title("🏃‍♂️ 체대입시 실기 가이드 & 보강운동")
    st.write("실제 체대입시 실기 배점 기준표를 바탕으로 점수를 계산하고 맞춤 보강운동을 안내합니다.")
    st.divider()

    # [입력 1] 성별 선택
    gender = st.radio("1. 성별을 선택하세요", ["남자", "여자"], horizontal=True)

    # [입력 2] 실기 종목 선택 (10m, 제자리 멀리뛰기 중 선택)
    event = st.selectbox("2. 실기 종목을 선택하세요", ["10m", "제자리 멀리뛰기"])

    # [입력 3] 선택한 종목에 따라 다른 기록 입력창 띄우기 (조건문)
    if event == "10m":
        record = st.number_input(
            "3. 10m 왕복달리기 기록을 입력하세요 (단위: 초)",
            min_value=5.0, max_value=20.0, value=8.80, step=0.05
        )
        unit = "초"
    else:
        record = st.number_input(
            "3. 제자리 멀리뛰기 기록을 입력하세요 (단위: cm)",
            min_value=100, max_value=350, value=275, step=1
        )
        unit = "cm"

    # 결과 확인 버튼 클릭 시 출력 화면 표시
    if st.button("실기 점수 및 보강운동 확인하기", type="primary"):
        score = calculate_score(gender, event, record)
        
        st.divider()
        st.subheader("📊 실기 측정 결과")
        
        # 점수 요약 표시
        col1, col2, col3 = st.columns(3)
        col1.metric("선택 성별 / 종목", f"{gender} / {event}")
        col2.metric("입력 기록", f"{record}{unit}")
        col3.metric("환산 점수", f"{score}점 / 100점")

        # 조건문으로 보강운동 필요 여부 판별 (90점 미만일 때 보강 필요)
        if score == 100:
            st.success("🏆 **만점입니다!** 보강운동이 필요하지 않습니다. 현재 컨디션 유지와 부상 방지에 집중하세요.")
        elif score >= 90:
            st.info("✅ **우수한 성적입니다!** 필수 보강운동은 없으나, 만점(100점) 도약을 위해 자세 교정을 추천합니다.")
        else:
            st.warning(f"⚠️ **보강운동이 필요합니다!** (현재 {score}점 → 목표 90점 이상)")
            st.write(f"### 💪 [{event}] 추천 보강운동 프로그램")
            
            # 반복문(for)으로 보강운동 리스트에서 데이터를 꺼내 표 형태로 정리
            exercise_rows = []
            for item in TRAINING_GUIDE[event]:
                exercise_rows.append({
                    "보강운동": item[0],
                    "횟수": item[1],
                    "주기": item[2]
                })
            
            # 표 형태로 화면에 출력 (인덱스 번호 숨김 처리)
            df = pd.DataFrame(exercise_rows)
            st.dataframe(df, use_container_width=True, hide_index=True)

if __name__ == "__main__":
    main()
